def _build_message_pair(user_content: str, assistant_content: str) -> dict[str, Any]:
    """Return a single training sample in chat format."""
    return {
        "messages": [
            {"role": "user", "content": user_content},
            {"role": "assistant", "content": assistant_content},
        ]
    }


def _generate_general_pairs(max_pairs: int) -> list[dict[str, Any]]:
    """Produce up to *max_pairs* general instruction-following pairs."""
    pairs: list[dict[str, Any]] = []
    templates = list(_GENERAL_TEMPLATES)  # copy so we can shuffle

    while len(pairs) < max_pairs:
        random.shuffle(templates)
        for user, assistant in templates:
            if len(pairs) >= max_pairs:
                break
            pairs.append(_build_message_pair(user, assistant))

    return pairs


def _truncate_article(text: str, max_chars: int = 2000) -> str:
    """Truncate article text for prompt context, keeping whole sentences."""
    if len(text) <= max_chars:
        return text
    truncated = text[:max_chars]
    # Try to cut at last sentence boundary
    for sep in ("।", ".", "\n"):
        idx = truncated.rfind(sep)
        if idx > max_chars // 2:
            return truncated[: idx + 1]
    return truncated + "..."


def _generate_news_pairs(
    articles_path: Path,
    max_pairs: int,
) -> list[dict[str, Any]]:
    """Read newspaper articles and generate summarization, headline, and QA pairs."""
    articles: list[dict[str, str]] = []
    with open(articles_path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                continue
            text = obj.get("text", "").strip()
            title = obj.get("title", "").strip()
            if text and title:
                articles.append({"text": text, "title": title})

    if not articles:
        print("ERROR: no valid articles found in", articles_path, file=sys.stderr)
        sys.exit(1)

    print(f"Loaded {len(articles)} articles from {articles_path}", file=sys.stderr)

    pairs: list[dict[str, Any]] = []
    random.shuffle(articles)

    for article in articles:
        if len(pairs) >= max_pairs:
            break
        text = _truncate_article(article["text"])
        title = article["title"]

        # --- Summarization pair ---
        prompt_tmpl = random.choice(_SUMMARIZE_PROMPTS)
        # Use the title + first ~200 chars as a pseudo-summary
        summary = title
        if len(article["text"]) > 200:
            first_sentence_end = article["text"].find("।", 50)
            if first_sentence_end > 0:
                summary = article["text"][: first_sentence_end + 1]
            else:
                summary = title
        pairs.append(_build_message_pair(prompt_tmpl.format(text=text), summary))

        if len(pairs) >= max_pairs:
            break

        # --- Headline generation pair ---
        headline_tmpl = random.choice(_HEADLINE_PROMPTS)
        pairs.append(_build_message_pair(headline_tmpl.format(text=text), title))

        if len(pairs) >= max_pairs:
            break

        # --- Q&A pair ---
        qa_tmpl = random.choice(_QA_PROMPTS)
        # Pseudo-answer from the title
        qa_answer = f"এই সংবাদের মূল বিষয় হলো: {title}"
        pairs.append(_build_message_pair(qa_tmpl.format(text=text), qa_answer))

    return pairs


