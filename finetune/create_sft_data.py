def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate Bangla SFT training data in JSONL chat format.",
    )
    parser.add_argument(
        "--mode",
        choices=["general", "news"],
        required=True,
        help="Data generation mode: 'general' for template pairs, 'news' for article-based pairs.",
    )
    parser.add_argument(
        "--articles",
        type=Path,
        default=None,
        help="Path to JSONL file of articles (required for news mode). Each line: {\"text\": ..., \"title\": ...}",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Output JSONL file path.",
    )
    parser.add_argument(
        "--max-pairs",
        type=int,
        default=5000,
        help="Maximum number of training pairs to generate (default: 5000).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducibility (default: 42).",
    )
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    random.seed(args.seed)

    if args.mode == "news" and args.articles is None:
        print("ERROR: --articles is required for news mode.", file=sys.stderr)
        sys.exit(1)

    if args.mode == "general":
        pairs = _generate_general_pairs(args.max_pairs)
    else:
        assert args.articles is not None
        pairs = _generate_news_pairs(args.articles, args.max_pairs)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as fh:
        for pair in pairs:
            fh.write(json.dumps(pair, ensure_ascii=False) + "\n")

    print(
        f"Wrote {len(pairs)} pairs to {args.output} (mode={args.mode})",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
