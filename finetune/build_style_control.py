def main() -> None:
    parser = argparse.ArgumentParser(description="Build expressive Bangla style-control SFT data")
    parser.add_argument("--output", type=Path, default=Path("finetune/data/sft_style_emotion.jsonl"))
    args = parser.parse_args()

    rows = build_examples()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"Wrote {len(rows):,} rows -> {args.output}")


if __name__ == "__main__":
    main()
